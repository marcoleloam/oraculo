"""Offline presentation of canonical project folders; never opens a vault or DB."""

from __future__ import annotations

from pathlib import PurePosixPath

from oraculo.memory.schema import corpus


def _css_string(value: str) -> str:
    # CSS escapes are not JSON escapes (e.g. \\n would render as the letter n).
    return (
        '"'
        + "".join(
            f"\\{ord(char):x} "
            if ord(char) < 32 or ord(char) == 127 or char in '\\"<>'
            else char
            for char in value
        )
        + '"'
    )


def project_labels_css(snapshot: dict, project_ids: list[str]) -> str:
    """Render selected metadata from `oraculo status` or a T3 project snapshot.

    T3 supplies `title`; the service supplies `path` (basename fallback). The
    caller exports the snapshot through supported tools. Selection is explicit
    so other projects' names/paths never appear in the generated artifact.
    """
    if not isinstance(snapshot, dict) or not project_ids:
        raise ValueError("project_labels_requires_snapshot_and_project_ids")
    if "ok" in snapshot:
        if snapshot["ok"] is not True:
            raise ValueError("project_labels_failed_status")
        snapshot = snapshot.get("data")
    if not isinstance(snapshot, dict) or not isinstance(snapshot.get("projects"), list):
        raise ValueError("project_labels_invalid_projects_snapshot")
    if snapshot.get("nextCursor") is not None:
        raise ValueError("project_labels_requires_complete_snapshot")
    selected = set(project_ids)
    paths = {}
    for project_id in selected:
        if project_id == "shared":
            raise ValueError("project_labels_shared_is_not_a_project")
        paths[project_id] = corpus(project_id)
    if len(set(paths.values())) != len(paths):
        raise ValueError("project_labels_path_collision")
    owners = {path: project_id for project_id, path in paths.items()}
    names = {}
    for project in snapshot["projects"]:
        if not isinstance(project, dict) or not isinstance(project.get("id"), str):
            raise ValueError("project_labels_invalid_project")
        project_id = project["id"]
        owner = owners.get(corpus(project_id))
        if owner is not None and owner != project_id:
            raise ValueError("project_labels_path_collision")
        if project_id not in selected:
            continue
        if project_id in names:
            raise ValueError("project_labels_duplicate_project")
        if (
            project.get("deletedAt") is not None
            or project.get("status", "registered") != "registered"
        ):
            raise ValueError("project_labels_inactive_project")
        name = project.get("title")
        if name is None:
            path = project.get("path")
            if not isinstance(path, str) or not PurePosixPath(path).is_absolute():
                raise ValueError("project_labels_missing_name")
            name = PurePosixPath(path).name
        if not isinstance(name, str) or not name.strip() or "\x00" in name:
            raise ValueError("project_labels_invalid_name")
        name.encode("utf-8")  # Reject unpaired JSON surrogates before any output.
        names[project_id] = name
    if set(names) != selected:
        raise ValueError("project_labels_unknown_project")
    rules = [
        "/* Generated by oraculo obsidian project-labels. Presentation only.\n"
        " * Disable this snippet to restore the original folder labels.\n"
        " * Regenerate from fresh metadata after project additions or renames.\n"
        " */\n"
    ]
    for project_id in sorted(selected):
        rules.append(
            '.workspace-leaf-content[data-type="file-explorer"] '
            f".nav-folder-title[data-path={_css_string(paths[project_id])}]\n"
            '  > .nav-folder-title-content:not([contenteditable="true"])::before {\n'
            f"  content: {_css_string(names[project_id] + ' — ')};\n"
            "  pointer-events: none;\n"
            "}\n"
        )
    return "\n".join(rules)
